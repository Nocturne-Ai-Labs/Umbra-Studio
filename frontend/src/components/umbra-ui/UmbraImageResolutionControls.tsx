'use client';

import React from 'react';
import { Images, Ratio } from 'lucide-react';
import { UmbraMegapixelControls } from './UmbraMegapixelControls';
import type { UmbraUiPipelineResolutionCapability } from '../../../../shared/umbra-ui/pipelineTypes';
import { inferUmbraImageAspectRatio, inferUmbraImageBaseResolution, type UmbraImageAspectPresetId } from '@/lib/umbraUiImageResolution';

interface UmbraImageResolutionControlsProps {
  aspectRatio: UmbraImageAspectPresetId;
  baseResolution: number;
  width: string;
  height: string;
  batchSize: number;
  resolution: UmbraUiPipelineResolutionCapability;
  onAspectRatioChange: (value: UmbraImageAspectPresetId) => void;
  onBaseResolutionChange: (value: number) => void;
  onDimensionsChange: (width: string, height: string, manual?: boolean) => void;
  onBatchSizeChange: (value: number) => void;
}

const inputClass = 'w-full rounded-md border border-white/10 bg-black/35 px-2.5 py-2 text-xs text-zinc-100 outline-none transition-colors focus:border-cyan-300/45';
const labelClass = 'text-[9px] font-black uppercase tracking-[0.14em] text-zinc-500';

export function UmbraImageResolutionControls({
  width,
  height,
  batchSize,
  resolution,
  onAspectRatioChange,
  onBaseResolutionChange,
  onDimensionsChange,
  onBatchSizeChange,
}: UmbraImageResolutionControlsProps) {
  const resolutionAdjustable = resolution.support === 'adjustable';

  return (
    <section className="overflow-hidden rounded-md border border-white/10 bg-white/[0.02]">
      <header className="flex min-h-9 items-center gap-2 border-b border-white/[0.08] px-2.5">
        <Ratio size={13} className="text-cyan-300" />
        <span className="text-[10px] font-black uppercase tracking-[0.12em] text-zinc-200">
          {resolutionAdjustable ? 'Aspect & Resolution' : 'Output'}
        </span>
        <span className="ml-auto font-mono text-[10px] text-cyan-100">{width}x{height}</span>
      </header>

      <div className="space-y-2.5 p-2.5">
        <div className="max-w-28">
          <label className="space-y-1.5">
            <span className={labelClass}>Batch Count</span>
            <input
              type="number"
              min={1}
              max={64}
              step={1}
              value={batchSize}
              onChange={(event) => onBatchSizeChange(Math.max(1, Math.min(64, Number(event.target.value) || 1)))}
              className={inputClass}
              title="Images generated by each queued prompt"
            />
          </label>
        </div>

        {resolutionAdjustable && <UmbraMegapixelControls width={Number(width)} height={Number(height)} bounds={resolution} onChange={(w, h) => {
          onAspectRatioChange(inferUmbraImageAspectRatio(w, h));
          onBaseResolutionChange(inferUmbraImageBaseResolution(w, h));
          onDimensionsChange(String(w), String(h));
        }} />}

        <div className="flex items-center gap-1.5 border-t border-white/[0.07] pt-2 font-mono text-[9px] text-zinc-600">
          <Images size={10} />
          <span>{batchSize} image{batchSize === 1 ? '' : 's'} per queue item</span>
        </div>
      </div>
    </section>
  );
}
